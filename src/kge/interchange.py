"""Versioned JSON interchange format for embedding KGE in other systems.

Every document is an envelope ``{"schema": "kge.interchange", "version": 1, "kind": ...}``.

- ``submission`` is the only kind that is *read*: statements another system proposes, with
  the source text they quote. A submission never becomes knowledge directly; it is staged as
  candidates and goes through validation and review like any other extraction (see
  :class:`SubmissionExtractor` and ``kge.api.KnowledgeGraph.submit``).
- ``knowledge``, ``candidates``, ``diff`` and ``audit_log`` are *written* by KGE.

``json_schema()`` returns the JSON Schema of all kinds; ``schemas/kge-interchange-v1.json``
is the committed copy for consumers outside Python. A change that breaks readers of an
existing kind needs a new ``VERSION``.
"""

from __future__ import annotations

import datetime as dt
import json
import re
from typing import Annotated, Any, Literal

from pydantic import BaseModel, ConfigDict, Field, ValidationError

from kge import audit
from kge.extract import ExtractionResult
from kge.models import (
    Assertion,
    Candidate,
    Entity,
    EntityRef,
    EpistemicType,
    Evidence,
    LiteralValue,
    Source,
    SourceKind,
    StagedCandidate,
)
from kge.store import Store
from kge.versioning import diff

SCHEMA = "kge.interchange"
VERSION = 1

Origin = Literal["llm", "deterministic"]
_SYSTEM_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$")


class InterchangeError(ValueError):
    """The document is not a valid interchange document of a supported version."""


class _Model(BaseModel):
    model_config = ConfigDict(extra="forbid")


class _Envelope(_Model):
    schema_: Literal["kge.interchange"] = Field("kge.interchange", alias="schema")
    version: Literal[1] = 1

    model_config = ConfigDict(extra="forbid", populate_by_name=True)

    def to_json(self) -> str:
        return self.model_dump_json(by_alias=True, indent=2) + "\n"

    def to_dict(self) -> dict[str, Any]:
        return dict(self.model_dump(mode="json", by_alias=True))


# ---------------------------------------------------------------- read: submissions


class SubmittedSource(_Model):
    uri: str = Field(min_length=1, description="stable identity; resubmitting it is a diff")
    title: str | None = None
    kind: Literal["document", "dataset", "llm"] = Field(
        "document", description="'llm' if the text itself was generated by a model"
    )
    content: str = Field(description="the text that quotes are checked against")


class SubmittedStatement(_Model):
    subject: str = Field(min_length=1)
    subject_type: str | None = None
    predicate: str = Field(min_length=1)
    object: str = Field(min_length=1)
    object_type: str | None = Field(None, description="entity type, for an entity object")
    object_datatype: str | None = Field(None, description="xsd datatype, for a literal object")
    #: inferences come from the reasoner only, so they cannot be submitted
    epistemic_type: Literal["fact", "hypothesis"] = "fact"
    confidence: float = Field(ge=0.0, le=1.0)
    quote: str = Field("", description="verbatim quote from source.content; facts need one")
    locator: str | None = None
    valid_from: dt.date | None = None
    valid_to: dt.date | None = None


class Submission(_Envelope):
    kind: Literal["submission"] = "submission"
    source: SubmittedSource
    statements: list[SubmittedStatement]


# ---------------------------------------------------------------- write: exports


class AssertionRecord(Assertion):
    """An assertion with the labels of its entities, so readers need no second lookup."""

    subject_label: str
    object_label: str | None = None


class KnowledgeDoc(_Envelope):
    kind: Literal["knowledge"] = "knowledge"
    head_changeset: int
    as_of_changeset: int | None = None
    as_of: dt.datetime | None = None
    include_hypotheses: bool
    assertions: list[AssertionRecord]
    entities: list[Entity]


class CandidatesDoc(_Envelope):
    kind: Literal["candidates"] = "candidates"
    head_changeset: int
    state: str | None
    candidates: list[StagedCandidate]


class DiffDoc(_Envelope):
    kind: Literal["diff"] = "diff"
    base: int
    target: int
    added: list[AssertionRecord]
    removed: list[AssertionRecord]


class AuditEntry(_Model):
    seq: int
    at: str
    actor: str
    action: str
    payload: dict[str, Any]


class AuditDoc(_Envelope):
    kind: Literal["audit_log"] = "audit_log"
    verified: bool
    verify_message: str
    entries: list[AuditEntry]


Document = Annotated[
    Submission | KnowledgeDoc | CandidatesDoc | DiffDoc | AuditDoc, Field(discriminator="kind")
]


class _AnyDocument(BaseModel):
    doc: Document


def json_schema() -> dict[str, Any]:
    schema = _AnyDocument.model_json_schema(by_alias=True)
    doc = schema["properties"]["doc"]
    out: dict[str, Any] = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": f"https://kge.invalid/schemas/{SCHEMA}/v{VERSION}.json",
        "title": f"{SCHEMA} v{VERSION}",
        **{k: v for k, v in doc.items()},
        "$defs": schema.get("$defs", {}),
    }
    return out


def parse(data: str | bytes | dict[str, Any]) -> BaseModel:
    """Read any interchange document. Raises :class:`InterchangeError` with a readable
    message for other formats, unsupported versions and invalid content."""
    if isinstance(data, str | bytes):
        try:
            data = json.loads(data)
        except ValueError as exc:
            raise InterchangeError(f"not JSON: {exc}") from exc
    if not isinstance(data, dict):
        raise InterchangeError("an interchange document is a JSON object")
    if data.get("schema") != SCHEMA:
        raise InterchangeError(f"not a {SCHEMA} document (schema={data.get('schema')!r})")
    if data.get("version") != VERSION:
        raise InterchangeError(
            f"unsupported {SCHEMA} version {data.get('version')!r}; this build reads {VERSION}"
        )
    try:
        return _AnyDocument.model_validate({"doc": data}).doc
    except ValidationError as exc:
        raise InterchangeError(f"invalid {data.get('kind')!r} document: {exc}") from exc


def parse_submission(data: str | bytes | dict[str, Any]) -> Submission:
    doc = parse(data)
    if not isinstance(doc, Submission):
        raise InterchangeError(f"expected a submission, got {doc.kind!r}")  # type: ignore[attr-defined]
    return doc


def submitter_id(system: str, origin: Origin) -> str:
    """The extractor id recorded for a submission. It is derived here, never taken from the
    document, so a submitter cannot pass model output off as a deterministic or human one."""
    if not _SYSTEM_NAME.match(system):
        raise InterchangeError(
            f"invalid system name {system!r}: use letters, digits, '.', '_' or '-' (max 64)"
        )
    if origin == "llm":
        return f"llm:external/{system}"
    if origin == "deterministic":
        return f"external:{system}"
    raise InterchangeError(f"origin must be 'llm' or 'deterministic', not {origin!r}")


class SubmissionExtractor:
    """Turns a submission into candidates for the normal ingestion pipeline."""

    def __init__(self, submission: Submission, system: str, origin: Origin) -> None:
        self.submission = submission
        self.id = submitter_id(system, origin)

    def extract(self, source: Source) -> ExtractionResult:
        out: list[Candidate] = []
        invalid: list[dict[str, Any]] = []
        for i, st in enumerate(self.submission.statements):
            try:
                obj: EntityRef | LiteralValue
                if st.object_datatype:
                    obj = LiteralValue(value=st.object, datatype=st.object_datatype)
                else:
                    obj = EntityRef(label=st.object, type=st.object_type)
                evidence = (
                    [
                        Evidence(
                            source_id=source.id,
                            source_version=source.version,
                            quote=st.quote,
                            locator=st.locator,
                        )
                    ]
                    if st.quote
                    else []
                )
                out.append(
                    Candidate(
                        subject=EntityRef(label=st.subject, type=st.subject_type),
                        predicate=st.predicate,
                        object=obj,
                        epistemic_type=EpistemicType(st.epistemic_type),
                        confidence=st.confidence,
                        confidence_method=f"submitted:{self.id}",
                        valid_from=st.valid_from,
                        valid_to=st.valid_to,
                        evidence=evidence,
                        extracted_by=self.id,
                    )
                )
            except ValidationError as exc:
                invalid.append({"index": i, "error": exc.errors(include_url=False)})
        return ExtractionResult(out, invalid)


def source_kind(submission: Submission) -> SourceKind:
    return SourceKind(submission.source.kind)


# ---------------------------------------------------------------- export builders


def _record(store: Store, a: Assertion) -> AssertionRecord:
    return AssertionRecord(
        **a.model_dump(),
        subject_label=store.label(a.subject),
        object_label=store.label(a.object_value) if a.object_kind == "entity" else None,
    )


def knowledge(
    store: Store,
    changeset: int | None = None,
    at: dt.datetime | None = None,
    include_hypotheses: bool = True,
) -> KnowledgeDoc:
    rows = store.snapshot(changeset, at, include_hypotheses=include_hypotheses)
    used = {a.subject for a in rows} | {a.object_value for a in rows if a.object_kind == "entity"}
    return KnowledgeDoc(
        head_changeset=store.head(),
        as_of_changeset=changeset,
        as_of=at,
        include_hypotheses=include_hypotheses,
        assertions=[_record(store, a) for a in rows],
        entities=[e for e in store.entities() if e.id in used],
    )


def candidates(store: Store, state: str | None = None) -> CandidatesDoc:
    from kge.models import CandidateState

    st = CandidateState(state) if state else None
    return CandidatesDoc(
        head_changeset=store.head(), state=state, candidates=store.candidates(state=st)
    )


def changes(store: Store, base: int, target: int) -> DiffDoc:
    d = diff(store, base, target)
    return DiffDoc(
        base=base,
        target=target,
        added=[_record(store, a) for a in d.added],
        removed=[_record(store, a) for a in d.removed],
    )


def audit_log(store: Store) -> AuditDoc:
    v = audit.verify(store.conn)
    return AuditDoc(
        verified=v.ok,
        verify_message=v.message,
        entries=[AuditEntry(**e) for e in audit.entries(store.conn)],
    )
